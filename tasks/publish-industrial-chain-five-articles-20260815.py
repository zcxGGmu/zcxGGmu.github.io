def write_outputs(outputs: dict[str, str], binary_outputs: dict[str, bytes]) -> None:
    out_dir = Path("/tmp/industrial-chain-five-articles-20260815-publish-output")
    if out_dir.exists():
        import shutil

        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for rel, content in outputs.items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for rel, content in binary_outputs.items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    print(json.dumps({"local_output": str(out_dir), "text_files": len(outputs), "binary_files": len(binary_outputs), "urls": [post.full_url for post in base.POSTS]}, ensure_ascii=False, indent=2))


def create_commit(outputs: dict[str, str], binary_outputs: dict[str, bytes], ref: base.RemoteRef) -> str:
    entries = []
    for path, content in sorted(outputs.items()):
        blob = base.run_gh(["-X", "POST", base.endpoint("git/blobs"), "--input", "-"], {"content": content, "encoding": "utf-8"})
        entries.append({"path": path, "mode": "100644", "type": "blob", "sha": blob["sha"]})
    for path, content in sorted(binary_outputs.items()):
        blob = base.run_gh(["-X", "POST", base.endpoint("git/blobs"), "--input", "-"], {"content": base64.b64encode(content).decode("ascii"), "encoding": "base64"})
        entries.append({"path": path, "mode": "100644", "type": "blob", "sha": blob["sha"]})
    tree = base.run_gh(["-X", "POST", base.endpoint("git/trees"), "--input", "-"], {"base_tree": ref.tree_sha, "tree": entries})
    commit = base.run_gh(
        ["-X", "POST", base.endpoint("git/commits"), "--input", "-"],
        {"message": "Publish five industrial chain deep dives", "tree": tree["sha"], "parents": [ref.commit_sha]},
    )
    base.run_gh(["-X", "PATCH", base.endpoint(f"git/refs/heads/{base.BRANCH}"), "--input", "-"], {"sha": commit["sha"], "force": False})
    return commit["sha"]


def main() -> None:
    global _active_ref
    for attempt in range(3):
        ref = base.get_ref()
        _active_ref = ref
        base.get_file = get_file_at_active_ref
        outputs = base.collect_outputs()
        binary_outputs = collect_binary_outputs()
        refresh_manifest(outputs, binary_outputs)
        validate(outputs, binary_outputs)
        write_outputs(outputs, binary_outputs)
        try:
            commit_sha = create_commit(outputs, binary_outputs, ref)
        except RuntimeError as exc:
            if attempt < 2 and "Reference update failed" in str(exc):
                continue
            raise
        for _ in range(6):
            current_head = base.get_ref().commit_sha
            if current_head == commit_sha:
                break
            comparison = base.run_gh([base.endpoint(f"compare/{commit_sha}...{current_head}")])
            if comparison.get("status") in {"ahead", "identical"}:
                break
            time.sleep(3)
        else:
            raise RuntimeError("published commit is not an ancestor of current remote head")
        print(json.dumps({"parent": ref.commit_sha, "pushed": commit_sha, "urls": [post.full_url for post in base.POSTS]}, ensure_ascii=False, indent=2))
        return
    raise RuntimeError("publication retried after concurrent updates but did not succeed")


if __name__ == "__main__":
    main()
